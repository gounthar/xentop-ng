use ratatui::style::Color;

/// Three-stop colour gradient, sampled with `at(0.0..=1.0)`.
#[derive(Clone, Copy)]
pub struct Gradient(pub [(u8, u8, u8); 3]);

impl Gradient {
    pub fn at(&self, f: f64) -> Color {
        let f = if f.is_finite() { f.clamp(0.0, 1.0) } else { 0.0 };
        let (a, b, t) = if f < 0.5 {
            (self.0[0], self.0[1], f * 2.0)
        } else {
            (self.0[1], self.0[2], (f - 0.5) * 2.0)
        };
        let l = |x: u8, y: u8| (x as f64 + (y as f64 - x as f64) * t).round() as u8;
        Color::Rgb(l(a.0, b.0), l(a.1, b.1), l(a.2, b.2))
    }
}

